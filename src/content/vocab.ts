import { stripStress } from '../core/text';

export interface Word {
  id: string;
  ru: string; // with stress marks
  translit: string;
  de: string;
  topic: string; // topic id or user set id
  note?: string;
  exRu?: string;
  exDe?: string;
}

export interface Topic {
  id: string;
  emoji: string;
  title: string;
  words: Word[];
}

type Raw = [ru: string, translit: string, de: string, extra?: { note?: string; ex?: [string, string] }];

export const wordId = (topic: string, ru: string) => `${topic}:${stripStress(ru).toLowerCase()}`;

const topic = (id: string, emoji: string, title: string, raw: Raw[]): Topic => ({
  id,
  emoji,
  title,
  words: raw.map(([ru, translit, de, extra]) => ({
    id: wordId(id, ru),
    ru,
    translit,
    de,
    topic: id,
    note: extra?.note,
    exRu: extra?.ex?.[0],
    exDe: extra?.ex?.[1],
  })),
});

